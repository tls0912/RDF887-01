package com.czkuo.rdf88701.common.enums;

/**
 * 由外部設定告訴系統應如何處理該裝置的連線行為。
 */
public enum ConnectionMode {

    /**
     * 關閉模式：
     * 系統不會建立連線，也不會自動重連。
     * 通常用於停用設備或明確指示不需通訊。
     */
    OFF,

    /**
     * 自動模式：
     * 系統應主動建立連線，並在斷線時自動補連。
     * 為預設建議值，適用於一般持續運作的設備。
     */
    AUTO,

    /**
     * 手動模式：
     * 僅允許外部主動呼叫建立連線（如 API / UI 介面），
     * 系統不會自動建立或補連。
     */
    MANUAL
}
